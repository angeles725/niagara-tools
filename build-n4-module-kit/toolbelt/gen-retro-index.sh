#!/usr/bin/env bash
# gen-retro-index.sh — generates retros/INDEX.md, the retro promotion registry, from each retro's header.
#
# INDEX.md used to be hand-edited: every kit PR appended or flipped a row, so parallel sessions
# conflicted on it and "keep both sides" resolutions flipped rows. The index is now DERIVED: one row
# per retros/*.md (INDEX.md excluded) built from header comments in the retro itself. To add or flip
# a row, edit the retro header and regenerate; on a merge conflict in INDEX.md, regenerate.
# [ev: retro generated-retro-index]
#
# Header contract (column-0 comments at the top of every retro):
#   <!-- review-status: pending|folded -->   within lines 1-5 (the sweep-build-state marker rule;
#                                            the first word after the colon is the status)
#   <!-- module: <Module|kit> -->            within lines 1-10, exactly one line
#   <!-- deltas: <N> -->                     within lines 1-10, N a non-negative integer
#   <!-- index-comment: <text> -->           optional, within lines 1-10; emitted as a trailing
#                                            `<!-- <text> -->` on the row (e.g. a sweep --age
#                                            `disposition: ...` that parks a non-retro doc)
# Date = the first YYYY-MM-DD in the filename. Rows sort by date, then filename (LC_ALL=C), so a new
# retro never lands at a position another session also edits. A retro missing any required header,
# or with no date in its name, is a contract violation (exit 1, nothing written).
#
# Mutation: GRI-stale -- dropping the generated-vs-committed compare makes --check vacuously clean
# Mutation: GRI-order -- sorting by filename only puts APPLY-PLAN (A > 2) after a later-dated retro
# Mutation: GRI-comment -- dropping the index-comment cell loses the disposition that sweep --age reads
# Mutation: GRI-required -- defaulting a missing header to an empty cell writes a row nobody can fold
#
# Usage:  gen-retro-index.sh [--check] [<kit-root>]     (default kit root: this script's ../)
# Exits:  0 written / index fresh · 1 stale or missing index under --check, or retro-header
#         violation · 3 usage/env (nothing written)
# VCS-free by design (kit-links L2). Deterministic: LC_ALL=C sort, no timestamps.
set -u
LC_ALL=C
export LC_ALL

usage_exit() {
  printf 'usage: gen-retro-index.sh [--check] [<kit-root>]\n' >&2
  exit 3
}

CHECK=0
ROOT=""
while [ $# -gt 0 ]; do
  case "$1" in
    --check) CHECK=1; shift ;;
    -*) usage_exit ;;
    *) [ -z "$ROOT" ] || usage_exit; ROOT="$1"; shift ;;
  esac
done
if [ -z "$ROOT" ]; then
  ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
fi
RD="$ROOT/retros"
[ -d "$RD" ] || { printf 'gen-retro-index: no retros/ under %s\n' "$ROOT" >&2; exit 3; }
OUT="$RD/INDEX.md"

# row_of <file> <name> — prints "date<TAB>row" or "ERR<TAB><reason>".
row_of() {
  awk -v name="$2" '
    function val(s, key) { sub("^<!-- " key ":[ \t]*", "", s); sub(/[ \t]*-->$/, "", s); return s }
    NR > 10 { exit }
    NR <= 5 && status == "" && /^<!--[ \t]*review-status:/ {
      s = $0; sub(/^<!--[ \t]*review-status:[ \t]*/, "", s); split(s, w, /[ \t]+/); status = w[1]
    }
    /^<!-- module:.*-->$/        { nmod++; module = val($0, "module") }
    /^<!-- deltas:.*-->$/        { ndel++; deltas = val($0, "deltas") }
    /^<!-- index-comment:.*-->$/ { comment = val($0, "index-comment") }
    END {
      date = ""
      if (match(name, /[0-9][0-9][0-9][0-9]-[0-9][0-9]-[0-9][0-9]/)) date = substr(name, RSTART, RLENGTH)
      if (status != "pending" && status != "folded") { print "ERR\tno <!-- review-status: pending|folded --> marker in lines 1-5"; exit }
      if (nmod != 1 || module == "" || module ~ /\|/) { print "ERR\tneeds exactly one <!-- module: <Module|kit> --> header in lines 1-10"; exit }
      if (ndel != 1 || deltas !~ /^[0-9]+$/) { print "ERR\tneeds exactly one <!-- deltas: <N> --> header (N an integer) in lines 1-10"; exit }
      if (date == "") { print "ERR\tno YYYY-MM-DD date in the filename"; exit }
      row = "| " name " | " module " | " date " | " status " | " deltas " |"
      if (comment != "") row = row " <!-- " comment " -->"
      printf "%s\t%s\n", date, row
    }
  ' "$1"
}

render() {
  cat <<'EOF'
<!-- GENERATED by toolbelt/gen-retro-index.sh from each retro's header comments. Do not edit by hand. -->
<!-- Regenerate: bash toolbelt/gen-retro-index.sh · freshness gate: bash toolbelt/gen-retro-index.sh --check · on a merge conflict, regenerate -->
# Retro index — the promotion registry for the build-n4-module kit

One row per retro in this directory, GENERATED from the header comments at the top of each retro
(`<!-- review-status: pending|folded -->`, `<!-- module: X -->`, `<!-- deltas: N -->`, optional
`<!-- index-comment: … -->`) and validated by `toolbelt/sweep-build-state.sh` + `tests/build-retro-sync.bats`.
Rows sort by date (the first YYYY-MM-DD in the filename), then filename. To add or flip a row, edit the
retro header and run `toolbelt/gen-retro-index.sh`; on a merge conflict in this file, regenerate it.
`review-status`: `pending` = a PROPOSED delta not yet folded into the kit core; `folded` = promoted.
`deltas` = number of Δ<n>-numbered proposed deltas the retro enumerates (0 = not enumerated).

| Retro file | Module | Date | review-status | deltas |
|---|---|---|---|---|
EOF
  local f name out
  for f in "$RD"/*.md; do
    [ -f "$f" ] || continue
    name="$(basename "$f")"
    [ "$name" = "INDEX.md" ] && continue
    if ! out="$(row_of "$f" "$name")" || [ -z "$out" ]; then
      printf 'gen-retro-index: %s: awk failed reading the header\n' "$name" >&2; printf '%s\n' "$ENV_MARK"; continue
    fi
    case "$out" in
      ERR*) printf 'gen-retro-index: %s: %s\n' "$name" "${out#ERR?}" >&2; printf '%s\n' "$BAD_MARK"; continue ;;
    esac
    printf '%s\t%s\n' "${out%%	*}" "$name	${out#*	}"
  done | sort -t '	' -k1,1 -k2,2 | cut -f3-
}

BAD_MARK='@@gen-retro-index-contract-violation@@'
ENV_MARK='@@gen-retro-index-awk-failure@@'
CONTENT="$(render)"
case "$CONTENT" in *"$ENV_MARK"*) { printf 'gen-retro-index: awk failed; index not written\n' >&2; exit 3; } ;; esac
case "$CONTENT" in *"$BAD_MARK"*) { printf 'gen-retro-index: retro-header violation; index not written\n' >&2; exit 1; } ;; esac

if [ "$CHECK" -eq 1 ]; then
  if [ ! -f "$OUT" ]; then
    printf 'gen-retro-index: %s is missing; run gen-retro-index.sh\n' "$OUT" >&2
    exit 1
  fi
  if [ "$CONTENT" != "$(cat "$OUT")" ]; then
    printf 'gen-retro-index: %s is stale; run gen-retro-index.sh and commit the result\n' "$OUT" >&2
    diff <(printf '%s\n' "$CONTENT") "$OUT" >&2 || true
    exit 1
  fi
  printf 'gen-retro-index: %s is fresh\n' "$OUT"
  exit 0
fi

printf '%s\n' "$CONTENT" > "$OUT"
printf 'gen-retro-index: wrote %s\n' "$OUT"
