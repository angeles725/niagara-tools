#!/usr/bin/env bash
# pr-size.sh — the PR size gate (the "400-line PR" rule of build-n4-module-kit/METHODOLOGY.md, enforced by
# .github/workflows/pr-size.yml). Counts the authored changed lines of a pull request and fails over the limit.
#
# Usage:  pr-size.sh <base> <head>     (run inside the repository; both are any commit-ish, e.g. SHAs)
# Env:    PR_SIZE_LIMIT   the limit, a positive integer (default 400; empty = default)
# Count:  additions + deletions of `git diff <base>...<head>` (the merge-base to head diff, i.e. what the PR itself
#         changes, not what landed on the base meanwhile). A pure rename counts 0; a rename with an edit counts the
#         edit; a binary file counts 0 (it shows `binary`).
# Excluded (listed per file, never counted): lines a reviewer does not author or read:
#         go.sum, *.lock, package-lock.json   dependency lock files, regenerated by a tool
#         testdata/**                         Go golden and fixture trees, written by the code under test
#         vendor/**                           vendored third-party code
#         Everything else counts, a changelog.d/ fragment included (it is authored prose a reviewer reads, and a few
#         lines of it do not decide the gate).
# Output: one line per file (`<added> <deleted> <path>`, or `excluded (+A -D) <path>`), then the total. A path is
#         printed shell-quoted (bash printf %q: a space or a control character is escaped), so a file name with a
#         newline cannot start a line of its own and inject a workflow command such as `::warning`.
# Exits:  0 at or under the limit · 1 over the limit · 3 usage/env (bad arguments or limit, an unknown ref, not a repo)
# The workflow waives exit 1 for a pull request that carries the `size:exception` label (scripts/pr-size-waiver.sh);
# this script does not know labels.
set -euo pipefail

die() { printf 'pr-size: %s\n' "$1" >&2; exit 3; }

[ "$#" -eq 2 ] || die "usage: pr-size.sh <base> <head>"
base="$1"
head="$2"

limit="${PR_SIZE_LIMIT:-400}"
[[ "$limit" =~ ^[1-9][0-9]*$ ]] || die "PR_SIZE_LIMIT must be a positive integer, got '$limit'"

git rev-parse --git-dir >/dev/null 2>&1 || die "not inside a git repository"
for ref in "$base" "$head"; do
  git rev-parse --verify --quiet "$ref^{commit}" >/dev/null || die "unknown ref or not a commit: $ref"
done

# show <path>: set $shown to the path as one printable line (a control character, a newline included, is escaped)
show() { printf -v shown '%q' "$1"; }

is_excluded() { # is_excluded <path>: 0 when the path is generated, a lock file or vendored
  case "$1" in
    go.sum | */go.sum | *.lock | package-lock.json | */package-lock.json) return 0 ;;
    testdata/* | */testdata/* | vendor/* | */vendor/*) return 0 ;;
  esac
  return 1
}

tmp="$(mktemp "${TMPDIR:-/tmp}/pr-size.XXXXXX")"
trap 'rm -f "$tmp"' EXIT
git diff --numstat -z -M "$base...$head" >"$tmp" || die "git diff $base...$head failed"

added=0 deleted=0 counted=0 excluded=0
printf 'pr-size: %s...%s\n' "$base" "$head"
# -z records: "<add>\t<del>\t<path>\0", and for a rename "<add>\t<del>\t\0<old>\0<new>\0".
while IFS= read -r -d '' rec; do
  a="${rec%%$'\t'*}"
  rest="${rec#*$'\t'}"
  d="${rest%%$'\t'*}"
  path="${rest#*$'\t'}"
  if [ -z "$path" ]; then
    IFS= read -r -d '' _old
    IFS= read -r -d '' path
  fi
  note=""
  if [ "$a" = "-" ]; then a=0 d=0 note=" (binary)"; fi
  if is_excluded "$path"; then
    excluded=$((excluded + 1))
    show "$path"
    printf '  excluded (+%s -%s) %s\n' "$a" "$d" "$shown"
    continue
  fi
  counted=$((counted + 1))
  added=$((added + a))
  deleted=$((deleted + d))
  show "$path"
  printf '  %6s %6s  %s%s\n' "$a" "$d" "$shown" "$note"
done <"$tmp"

total=$((added + deleted))
printf 'pr-size: total %s changed lines (+%s -%s) in %s file(s), limit %s, %s file(s) excluded\n' \
  "$total" "$added" "$deleted" "$counted" "$limit" "$excluded"
if [ "$total" -gt "$limit" ]; then
  printf 'pr-size: FAIL: %s changed lines exceeds the %s-line limit. Split the work into a chain of smaller PRs, or ask a maintainer for the size:exception label when the diff is unavoidable.\n' "$total" "$limit"
  exit 1
fi
printf 'pr-size: OK: within the %s-line limit\n' "$limit"
