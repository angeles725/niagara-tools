// Values from CPython 3.15 (unicodedata 17.0.0).
func TestStrFacts(t *testing.T) {
	for _, tc := range []struct {
		r                             rune
		space, alnum, decimal, isWord bool
	}{
		{' ', true, false, false, false}, {0x1c, true, false, false, false}, {0x85, true, false, false, false},
		{0x3000, true, false, false, false}, {0x200b, false, false, false, false}, {'_', false, false, false, true},
		{'a', false, true, false, true}, {'7', false, true, true, true}, {'½', false, true, false, true},
		{'٣', false, true, true, true}, {'ñ', false, true, false, true}, {0x301, false, false, false, false},
		{0xfffd, false, false, false, false},
	} {
		if IsSpace(tc.r) != tc.space || IsAlnum(tc.r) != tc.alnum || IsDecimal(tc.r) != tc.decimal || IsWord(tc.r) != tc.isWord {
			t.Errorf("%U: space %v alnum %v decimal %v word %v", tc.r, IsSpace(tc.r), IsAlnum(tc.r), IsDecimal(tc.r), IsWord(tc.r))
		}
	}
}

func TestFolds(t *testing.T) {
	for _, tc := range []struct{ in, marks, fold string }{
		{"Presión", "Presion", "presión"},
		{"ﬁltro", "filtro", "filtro"},
		{"ＡＢＣ", "ABC", "ａｂｃ"},
		{"한", "한", "한"},
		{"Straße", "Straße", "strasse"},
		{"ΣΑΣ", "ΣΑΣ", "σασ"},
		{"İ", "I", "i̇"},
		{"½", "1⁄2", "½"},
		{"á\xed\xa0\x80", "a\xed\xa0\x80", "á\xed\xa0\x80"}, // a lone surrogate's bytes are kept
	} {
		if got := StripMarks(tc.in); got != tc.marks {
			t.Errorf("StripMarks(%q) = %q, want %q", tc.in, got, tc.marks)
		}
		if got := CaseFold(tc.in); got != tc.fold {
			t.Errorf("CaseFold(%q) = %q, want %q", tc.in, got, tc.fold)
		}
	}
	if got := CollapseSpace("\t a  \n b　"); got != " a b " {
		t.Errorf("CollapseSpace = %q", got)
	}
	if got := Strip("\u0085 x y\x1f "); got != "x y" {
		t.Errorf("Strip = %q", got)
	}
}

// genPy writes unicode.txt from the running Python's unicodedata.
const genPy = `import sys, unicodedata as u
def ranges(pred):
    out, lo = [], None
    for cp in range(0x80, 0x110000):
        ok = pred(chr(cp))
        if ok and lo is None: lo = cp
        if not ok and lo is not None: out.append((lo, cp - 1)); lo = None
    if lo is not None: out.append((lo, 0x10FFFF))
    return ["%04X-%04X" % r for r in out]
def base(c):
    return "".join(x for x in u.normalize("NFKD", c) if not u.combining(x))
def rows(kind, items, n=20):
    return ["%s %s" % (kind, " ".join(items[i:i + n])) for i in range(0, len(items), n)]
def maps(f):
    out = []
    for cp in range(0x80, 0x110000):
        if 0xD800 <= cp <= 0xDFFF or 0xAC00 <= cp <= 0xD7A3 and f is base: continue
        v = f(chr(cp))
        if v and v != chr(cp): out.append("%04X:%s" % (cp, ".".join("%04X" % ord(x) for x in v)))
    return out
out = ["# generated by go/internal/htmltext TestUnicodeTable (HTMLTEXT_REGEN=1): Python %s, Unicode %s; do not edit" % (sys.version.split()[0], u.unidata_version)]
out += rows("e", ranges(lambda c: base(c) == "" and not (0xD800 <= ord(c) <= 0xDFFF)))
out += rows("d", maps(base))
out += rows("s", ["%04X" % cp for cp in range(0x80, 0x110000) if chr(cp).isspace()])
out += rows("f", maps(str.casefold))
out += rows("a", ranges(str.isalnum))
out += rows("n", ranges(str.isdecimal))
print("\n".join(out))
`

// TestUnicodeTable: the table loads; with HTMLTEXT_PARITY=1 and the python3 on PATH the version the table
// names, the table must be what that Python generates (about 4 s); HTMLTEXT_REGEN=1 rewrites it from python3.
func TestUnicodeTable(t *testing.T) {
	if !strings.HasPrefix(data().header, "# generated by") || len(data().fold) < 1000 || len(data().base) < 5000 {
		t.Fatalf("unicode.txt not loaded: %q", data().header)
	}
	regen := os.Getenv("HTMLTEXT_REGEN") == "1"
	if !regen && os.Getenv("HTMLTEXT_PARITY") != "1" {
		t.Skip("HTMLTEXT_PARITY unset")
	}
	ver, err := exec.Command("python3", "-I", "-c", `import sys, unicodedata as u; print("Python %s, Unicode %s" % (sys.version.split()[0], u.unidata_version))`).Output()
	if err != nil {
		t.Fatal(err)
	}
	if !regen && !strings.HasSuffix(data().header, ": "+strings.TrimSpace(string(ver))+"; do not edit") {
		t.Skipf("python3 is not the table's Python: %s", ver)
	}
	out, err := exec.Command("python3", "-I", "-c", genPy).Output()
	if err != nil {
		t.Fatal(err)
	}
	if regen {
		if err := os.WriteFile("unicode.txt", out, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	if string(out) != unicodeTxt {
		t.Error("unicode.txt differs from what its Python generates (rerun with HTMLTEXT_REGEN=1)")
	}
}
