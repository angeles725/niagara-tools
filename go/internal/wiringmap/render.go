package wiringmap

import (
	"fmt"
	"io"
	"path/filepath"
)

const (
	header = "<!-- Fill in the RT-slot, Full-ord and Notes columns before commissioning hand-off. -->\n" +
		"<!-- Rule: operator must not hand-derive the crossing  [ev: retro live-commissioning-verification-gaps Δ6] -->\n\n"
	table1 = "## Table 1 — OPERATOR config slots (facade → control)\n\n" +
		"These slots carry operator-visible setpoints and mode choices.\n" +
		"Each facade slot must be **linked facade→control** (the facade is the SOURCE, not the TARGET).\n\n" +
		"| Facade slot | Workbench display name | Target RT slot | Full ord | Physical instance / crossing notes |\n" +
		columns
	table2 = "\n## Table 2 — SUMMARY display slots (control → facade)\n\n" +
		"These slots display telemetry linked FROM the control module.\n" +
		"Each facade slot must be **linked control→facade** (the control point is the SOURCE).\n" +
		"A slot the component sets itself (timer anchor, computed status) is not linked: write `self` in its\n" +
		"Source RT slot cell. lint-link-target-flags.sh treats a row as a link-in target only once its source is filled.\n\n" +
		"| Facade slot | Workbench display name | Source RT slot | Full ord | Physical instance / crossing notes |\n" +
		columns
	columns   = "|-------------|------------------------|----------------|----------|-------------------------------------|\n"
	checklist = "\n## Per-instance commissioning checklist (BUILD-LOOP §6.b)\n\n" +
		"Run after wiring, before operator hand-off:\n\n" +
		"- [ ] Every OPERATOR config slot linked facade→control (not to a display slot, not to a link-target side)\n" +
		"- [ ] Every SUMMARY display slot linked control→facade\n" +
		"- [ ] Physical mapping / crossing documented in the Notes columns above\n" +
		"- [ ] Config sanity: interval > duration, setpoints ≠ 0, hasDefrost=true AND airDefrost=true on air-defrost units\n" +
		"- [ ] After hot reload: triage-console.sh clean (no own-module load failures)\n" +
		"- [ ] After hot reload: bog-audit.sh CHECK11 clean (proxy-link fallback set)\n" +
		"- [ ] obix-nav.py facade<->rt link batch audit: all expected links present and values in range\n"
)

// render writes the map of the facade source tree src: its two link tables, each row a slot to fill, and the
// commissioning checklist.
func render(w io.Writer, src string, op, sum []row) {
	fmt.Fprintf(w, "# Wiring Map — %s\n<!-- Generated by generate-wiring-map.sh from %s -->\n%s", filepath.Base(src), src, header)
	fmt.Fprint(w, table1)
	table(w, op, "| _(no OPERATOR slots found — check src dir or slot flags)_ | | | | |\n")
	fmt.Fprint(w, table2)
	table(w, sum, "| _(no SUMMARY display slots found — check src dir or slot flags)_ | | | | |\n")
	fmt.Fprint(w, checklist)
}

func table(w io.Writer, rows []row, none string) {
	for _, r := range rows {
		fmt.Fprintf(w, "| `%s` | %s | _(fill)_ | _(fill)_ | |\n", r.slot, r.display)
	}
	if len(rows) == 0 {
		fmt.Fprint(w, none)
	}
}
