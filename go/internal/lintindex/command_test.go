const usageLine = "usage: gen-lint-index.sh [--check] [<kit-root>]\n"

// kit makes a kit root whose toolbelt/ holds the given files.
func kit(t *testing.T, files map[string]string) (root, tb string) {
	t.Helper()
	root = t.TempDir()
	tb = filepath.Join(root, "toolbelt")
	if err := os.Mkdir(tb, 0o755); err != nil {
		t.Fatal(err)
	}
	for name, text := range files {
		if err := os.WriteFile(filepath.Join(tb, name), []byte(text), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	return root, tb
}

// run calls Main with buffers; defaultRoot is what the wrapper would export.
func run(defaultRoot string, args ...string) (code int, out, errs string) {
	var o, e bytes.Buffer
	s := cli.Stdio{Out: &o, Err: &e, Getenv: func(name string) string {
		if name == DefaultRootEnv {
			return defaultRoot
		}
		return ""
	}}
	code = Main(args, s)
	return code, o.String(), e.String()
}

func read(t *testing.T, path string) string {
	t.Helper()
	b, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	return string(b)
}

const header = "<!-- GENERATED by toolbelt/gen-lint-index.sh from each toolbelt/lint-*.sh header. Do not edit by hand. -->\n"

func TestMainUsageAndEnv(t *testing.T) {
	t.Parallel()
	root, _ := kit(t, nil)
	for _, args := range [][]string{{"--bogus", root}, {root, root}, {"-"}, {root, "-x"}, {"--"}} {
		code, out, errs := run("", args...)
		if code != ExitEnv || out != "" || errs != usageLine {
			t.Errorf("GLI-usage %q: got (%d, %q, %q)", args, code, out, errs)
		}
	}
	nope := filepath.Join(t.TempDir(), "nope")
	if code, out, errs := run("", nope); code != ExitEnv || out != "" || errs != "gen-lint-index: no toolbelt/ under "+nope+"\n" {
		t.Errorf("GLI-env: got (%d, %q, %q)", code, out, errs)
	}
	if code, _, errs := run(""); code != ExitEnv || !strings.Contains(errs, DefaultRootEnv) {
		t.Errorf("no root and no default: got (%d, %q)", code, errs)
	}
}

func TestMainGenerate(t *testing.T) {
	t.Parallel()
	root, tb := kit(t, map[string]string{
		"lint-alpha.sh": lint("lint-alpha.sh", "flags alpha things.", "lint-alpha.sh <src-root>", "0 clean · 1 any FAIL · 3 usage/env"),
		"lint-beta.sh":  lint("lint-beta.sh", "flags beta things.", "lint-beta.sh <src-root>", "0 clean"),
		"helper.sh":     "#!/usr/bin/env bash\n# helper.sh — not a lint\n",
		"report-module.sh": "#!/usr/bin/env bash\n# lint-beta.sh is documented here but never run.\n" +
			"a_out=$(\"$TOOLBELT/lint-alpha.sh\" \"$ADIR/src\" 2>&1) || a_exit=$?\n",
	})
	if err := os.Mkdir(filepath.Join(tb, "lint-dir.sh"), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.Symlink("nowhere", filepath.Join(tb, "lint-broken.sh")); err != nil {
		t.Fatal(err)
	}
	out := filepath.Join(tb, "INDEX.md")
	code, stdout, errs := run("", root)
	if code != ExitOK || stdout != "gen-lint-index: wrote "+out+"\n" || errs != "" {
		t.Fatalf("GLI-rows: got (%d, %q, %q)", code, stdout, errs)
	}
	got := read(t, out)
	wantRows := "| `toolbelt/lint-alpha.sh` | flags alpha things. | `lint-alpha.sh <src-root>` | 0 clean · 1 any FAIL · 3 usage/env | yes | — |\n" +
		"| `toolbelt/lint-beta.sh` | flags beta things. | `lint-beta.sh <src-root>` | 0 clean | no | — |\n"
	if !strings.HasPrefix(got, header) || !strings.HasSuffix(got, "|---|---|---|---|---|---|\n"+wantRows) {
		t.Errorf("GLI-rows: index =\n%s", got)
	}

	// GLI-fresh: --check right after a generate is fresh, a re-generate is byte-identical.
	if code, stdout, errs := run("", "--check", root); code != ExitOK || stdout != "gen-lint-index: "+out+" is fresh\n" || errs != "" {
		t.Errorf("GLI-fresh: got (%d, %q, %q)", code, stdout, errs)
	}
	if run("", root); read(t, out) != got {
		t.Error("GLI-fresh: a re-generate is not byte-identical")
	}
	// Extra trailing newlines in the committed file are ignored, as the bash $(...) compare did.
	if err := os.WriteFile(out, []byte(got+"\n\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if code, _, _ := run("", "--check", "--check", root); code != ExitOK {
		t.Errorf("trailing newlines: --check = %d, want 0", code)
	}

	// GLI-stale + GLI-check-readonly: a new lint makes --check exit 1 and never writes.
	if err := os.WriteFile(filepath.Join(tb, "lint-new.sh"), []byte(lint("lint-new.sh", "n", "u", "e")), 0o644); err != nil {
		t.Fatal(err)
	}
	before := read(t, out)
	code, stdout, errs = run("", "--check", root)
	if code != ExitStale || stdout != "" || !strings.HasPrefix(errs, "gen-lint-index: "+out+" is stale; run gen-lint-index.sh and commit the result\n") {
		t.Errorf("GLI-stale: got (%d, %q, %q)", code, stdout, errs)
	}
	if read(t, out) != before {
		t.Error("GLI-check-readonly: --check wrote INDEX.md")
	}
}

