func TestMainContractViolation(t *testing.T) {
	t.Parallel()
	root, tb := kit(t, map[string]string{
		"lint-ok.sh":      lint("lint-ok.sh", "fine.", "u", "e"),
		"lint-noexit.sh":  lint("lint-noexit.sh", "no exit line.", "u", ""),
		"lint-nousage.sh": lint("lint-nousage.sh", "no usage line.", "", "e"),
	})
	code, stdout, errs := run("", root)
	want := "gen-lint-index: lint-noexit.sh: no \"# Exit:\"/\"# Exits:\" line in the header (the leading comment block)\n" +
		"gen-lint-index: lint-nousage.sh: no \"# Usage:\" line in the header (the leading comment block)\n" +
		"gen-lint-index: header-contract violation; index not written\n"
	if code != ExitStale || stdout != "" || errs != want {
		t.Errorf("GLI-contract: got (%d, %q, %q)", code, stdout, errs)
	}
	if _, err := os.Stat(filepath.Join(tb, "INDEX.md")); err == nil {
		t.Error("GLI-contract: INDEX.md written despite a violation")
	}
}

// TestMainUnreadableHeader is the Go form of GLI-awkfail: a header that cannot be read is exit 3
// and the committed INDEX.md is left untouched, even when another lint also breaks the contract.
func TestMainUnreadableHeader(t *testing.T) {
	t.Parallel()
	if os.Geteuid() == 0 {
		t.Skip("root reads a mode-000 file")
	}
	root, tb := kit(t, map[string]string{"lint-a.sh": lint("lint-a.sh", "a", "u", "e")})
	if code, _, _ := run("", root); code != ExitOK {
		t.Fatal("seed generate failed")
	}
	out := filepath.Join(tb, "INDEX.md")
	before := read(t, out)
	locked := filepath.Join(tb, "lint-locked.sh")
	if err := os.WriteFile(locked, []byte(lint("lint-locked.sh", "l", "u", "e")), 0); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(tb, "lint-nousage.sh"), []byte(lint("lint-nousage.sh", "x", "", "e")), 0o644); err != nil {
		t.Fatal(err)
	}
	code, stdout, errs := run("", root)
	if code != ExitEnv || stdout != "" ||
		!strings.HasPrefix(errs, "gen-lint-index: lint-locked.sh: cannot read the header: ") ||
		!strings.HasSuffix(errs, "gen-lint-index: lint-nousage.sh: no \"# Usage:\" line in the header (the leading comment block)\n"+
			"gen-lint-index: a lint header could not be read; index not written\n") {
		t.Errorf("got (%d, %q, %q)", code, stdout, errs)
	}
	if read(t, out) != before {
		t.Error("INDEX.md changed after a read failure")
	}
}

// TestMainWriteFailure: an index that cannot be written is exit 3, never "wrote" (the bash tool
// printed "wrote" and exited 0 after a failed redirect).
func TestMainWriteFailure(t *testing.T) {
	t.Parallel()
	if os.Geteuid() == 0 {
		t.Skip("root writes into a mode-555 directory")
	}
	root, tb := kit(t, map[string]string{"lint-a.sh": lint("lint-a.sh", "a", "u", "e")})
	if err := os.Chmod(tb, 0o555); err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = os.Chmod(tb, 0o755) })
	code, stdout, errs := run("", root)
	if code != ExitEnv || stdout != "" || !strings.HasPrefix(errs, "gen-lint-index: cannot write "+filepath.Join(tb, "INDEX.md")+": ") {
		t.Errorf("got (%d, %q, %q)", code, stdout, errs)
	}
}

// TestMainRealKit is GLI-real, GLI-wp and GLI-timers: the committed kit index is fresh and keeps
// the full wrapped exit contracts.
func TestMainRealKit(t *testing.T) {
	t.Parallel()
	root := filepath.Join("..", "..", "..", "build-n4-module-kit")
	code, stdout, errs := run(root, "--check")
	if code != ExitOK || errs != "" || !strings.HasSuffix(stdout, " is fresh\n") {
		t.Fatalf("GLI-real: got (%d, %q, %q)", code, stdout, errs)
	}
	index := read(t, filepath.Join(root, "toolbelt", "INDEX.md"))
	for _, want := range []string{
		"under --strict · 3 usage/env/missing-matrix or a sub-directory find cannot enter (K20) |",
		"2 usage · 3 env (incl. a sub-directory find cannot enter) |",
	} {
		if !strings.Contains(index, want) {
			t.Errorf("committed INDEX.md lacks %q", want)
		}
	}
}
