package lintindex

import "strings"

// dash is a table cell's text, or — when empty.
func dash(s string) string {
	if s == "" {
		return "—"
	}
	return s
}

// Markdown is the row's line of the index table. Each usage line is its own code span; a usage
// that already holds a backtick is kept as written.
func (r Row) Markdown() string {
	ucell := r.Usage
	if !strings.Contains(ucell, "`") {
		ucell = "`" + strings.ReplaceAll(ucell, "<br>", "`<br>`") + "`"
	}
	auto := "no"
	if r.Auto {
		auto = "yes"
	}
	return "| `toolbelt/" + r.Name + "` | " + r.Desc + " | " + ucell + " | " + r.Exit + " | " + auto + " | " +
		dash(r.Ev) + " | " + dash(r.Guide) + " | " + dash(r.Doc) + " |"
}

const preamble = "<!-- GENERATED by toolbelt/gen-lint-index.sh from each toolbelt/lint-*.sh header — do not edit; not committed, regenerated on pull -->\n" +
	"<!-- Print: bash toolbelt/kit-state.sh lint-index · regenerate: bash toolbelt/kit-state.sh --write · validate: bash toolbelt/gen-lint-index.sh --check -->\n" +
	"# Toolbelt lint index\n" +
	"\n" +
	"One row per `toolbelt/lint-*.sh`, derived from the script's own header: the description (line 2,\n" +
	"`# <name> — <what it checks>`, up to header line 5), every `Usage:` line, every `Exit:`/`Exits:` line\n" +
	"(wrapped lines joined; several lines separated by a line break) and its evidence tags. **Auto** says\n" +
	"whether `report-module.sh` (run by `build.sh` after every successful build) invokes the lint; a `no`\n" +
	"lint is run by hand on the profiles its usage names. **Guide** lists every `types/*.md:<line>` that names\n" +
	"the script and **Doc** the `[CERT-doc]` / `niagara-help/` citation within 6 lines of such a line (`—` for\n" +
	"none); `gen-lint-index.sh --check-guides` fails a lint no guide names unless its header says `# Scope: kit`.\n" +
	"\n" +
	"To add a lint: write its header to this contract and commit the lint alone; this file is not committed\n" +
	"(.gitignore), so two PRs that each add a lint never conflict here. Never edit this file and never\n" +
	"enumerate or count lints in BUILD-LOOP.md prose. [ev: retro kit-meta-hygiene-2026-10-01 Δ3]\n" +
	"[ev: retro ledger-generated-not-committed]\n" +
	"\n" +
	"| Lint | What it checks | Usage | Exit contract | Auto | Evidence | Guide | Doc |\n" +
	"|---|---|---|---|---|---|---|---|"

// Render is the whole index for rows in order, without a trailing newline.
func Render(rows []Row) string {
	var b strings.Builder
	b.WriteString(preamble)
	for _, r := range rows {
		b.WriteString("\n")
		b.WriteString(r.Markdown())
	}
	return b.String()
}
